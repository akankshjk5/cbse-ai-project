-- School-scoped lesson reuse, and the version dimensions that make a cache
-- entry safe to invalidate.
--
-- Reuse was per-teacher: `reserve_cloud_lesson` matched sources on
-- `owner_id = clerk_user_id()`. For a fixed NCERT catalogue that is close to no
-- cache at all — the whole economic argument is that one Class 10 "Light"
-- lesson serves a whole school, and per-teacher scoping makes every teacher pay
-- for it again. This widens the SOURCE lookup to the caller's school while
-- leaving ownership alone: each teacher still gets their own project row, their
-- own RLS scope and their own library entry, but the visuals are copied at zero
-- provider cost.
--
-- It also adds the dimensions a reuse key needs in order to expire. Matching on
-- class + subject + topic + duration + style + language alone means a lesson
-- generated by an older model, or against a superseded syllabus, is reused
-- forever with no way to retire it.
--
-- Deliberately NOT similarity-based. Reuse is an exact match on every dimension
-- below; two topics that read alike are two lessons.

-- ── Tenancy ─────────────────────────────────────────────────────────────────
-- Minimal on purpose: enough to answer "which school is this teacher in", which
-- is all reuse scoping needs. Billing and seat management are a later concern.

create table if not exists public.organizations (
  id uuid primary key default extensions.gen_random_uuid(),
  name text not null check (char_length(btrim(name)) between 2 and 200),
  created_at timestamptz not null default now()
);

create table if not exists public.schools (
  id uuid primary key default extensions.gen_random_uuid(),
  org_id uuid references public.organizations (id) on delete set null,
  name text not null check (char_length(btrim(name)) between 2 and 200),
  -- Matches the board list the deck form validates against (src/lib/boards.ts).
  board text not null default 'CBSE' check (char_length(btrim(board)) between 2 and 100),
  created_at timestamptz not null default now()
);
create index if not exists schools_org_idx on public.schools (org_id);

create table if not exists public.memberships (
  user_id text not null,
  school_id uuid not null references public.schools (id) on delete cascade,
  role text not null default 'teacher' check (role in ('teacher', 'head', 'admin')),
  created_at timestamptz not null default now(),
  primary key (user_id, school_id)
);
create index if not exists memberships_school_idx on public.memberships (school_id);

alter table public.organizations enable row level security;
alter table public.schools enable row level security;
alter table public.memberships enable row level security;

-- A member reads their own school and its organization, and their own
-- membership row. Nobody writes these from the client: schools are provisioned
-- by an operator holding the service role.
create policy "organizations: read own" on public.organizations
  for select to authenticated using (
    exists (
      select 1 from public.schools s
      join public.memberships m on m.school_id = s.id
      where s.org_id = organizations.id and m.user_id = public.clerk_user_id()
    )
  );

create policy "schools: read own" on public.schools
  for select to authenticated using (
    exists (
      select 1 from public.memberships m
      where m.school_id = schools.id and m.user_id = public.clerk_user_id()
    )
  );

create policy "memberships: read own" on public.memberships
  for select to authenticated using (user_id = public.clerk_user_id());

revoke all on table public.organizations from anon, authenticated;
revoke all on table public.schools from anon, authenticated;
revoke all on table public.memberships from anon, authenticated;
grant select on table public.organizations to authenticated;
grant select on table public.schools to authenticated;
grant select on table public.memberships to authenticated;
grant select, insert, update, delete on table public.organizations to service_role;
grant select, insert, update, delete on table public.schools to service_role;
grant select, insert, update, delete on table public.memberships to service_role;

-- The caller's school, or null when they belong to none. A teacher in two
-- schools reuses from the one they joined first, so the answer is stable
-- between calls rather than depending on row order.
create or replace function public.current_school_id()
returns uuid
language sql
stable
security definer
set search_path = ''
as $$
  select m.school_id
  from public.memberships m
  where m.user_id = public.clerk_user_id()
  order by m.created_at, m.school_id
  limit 1;
$$;
revoke all on function public.current_school_id() from public, anon;
grant execute on function public.current_school_id() to authenticated, service_role;

-- ── Reuse dimensions ────────────────────────────────────────────────────────
-- Stamped on the project at reservation, never written by a client. Every one
-- of them must match for a source to be reusable.

alter table public.cloud_lesson_projects
  add column if not exists school_id uuid references public.schools (id) on delete set null,
  add column if not exists chapter text
    check (chapter is null or char_length(btrim(chapter)) between 1 and 200),
  add column if not exists difficulty text not null default 'standard'
    check (difficulty in ('foundational', 'standard', 'advanced')),
  -- The syllabus edition the content was written against. Bumping it retires
  -- every cached lesson that predates the revision.
  add column if not exists curriculum_version text not null default 'NCERT-2023'
    check (char_length(btrim(curriculum_version)) between 2 and 40),
  -- The model and prompt generation that produced it. Bump this in
  -- `private.cloud_lesson_generator_version()` when the planner, image model or
  -- video provider changes, and no older lesson is reused again.
  add column if not exists generator_version text not null default 'v1'
    check (char_length(btrim(generator_version)) between 1 and 40);

-- The reuse-source lookup's predicate, in its selectivity order.
create index if not exists cloud_lesson_reuse_scope_idx
  on public.cloud_lesson_projects (
    content_key, visual_style, language_code,
    curriculum_version, generator_version, difficulty, completed_at desc
  )
  where status = 'succeeded' and reused_from_project_id is null;

create index if not exists cloud_lesson_school_idx
  on public.cloud_lesson_projects (school_id, content_key)
  where school_id is not null;

-- One constant, so bumping the generation is a one-line migration rather than a
-- redeploy.
create or replace function private.cloud_lesson_generator_version()
returns text
language sql
immutable
set search_path = ''
as $$ select 'v1'::text $$;
revoke all on function private.cloud_lesson_generator_version()
  from public, anon, authenticated, service_role;

-- ── Reservation ─────────────────────────────────────────────────────────────
-- Same body as 20261011150000, with three changes, each marked below:
--   1. the caller's school is resolved and stamped on the new project
--   2. the reuse SOURCE may belong to the caller OR to their school
--   3. every version dimension must match
-- Dropped rather than replaced: the two new parameters change the signature,
-- and an overload would make the six-argument call ambiguous. PostgREST binds
-- by name, so the existing caller keeps working against the defaults.

drop function if exists public.reserve_cloud_lesson(smallint, text, text, text, smallint, text);

create function public.reserve_cloud_lesson(
  p_class_level smallint, p_subject text, p_topic text, p_language_code text,
  p_target_duration_seconds smallint default 60, p_visual_style text default 'illustrated',
  p_chapter text default null, p_difficulty text default 'standard'
) returns setof public.cloud_lesson_projects
language plpgsql security definer set search_path = '' as $$
declare
  v_owner text := public.clerk_user_id();
  v_school uuid;
  v_key text;
  v_curriculum text := 'NCERT-2023';
  v_generator text := private.cloud_lesson_generator_version();
  v_chapter text := nullif(btrim(coalesce(p_chapter, '')), '');
  v_project public.cloud_lesson_projects;
  v_source public.cloud_lesson_projects;
begin
  if v_owner is null then
    raise exception 'Sign in to generate a lesson.' using hint = 'cloud_lesson_auth';
  end if;
  if p_class_level is null or p_class_level not between 1 and 12
    or char_length(btrim(coalesce(p_subject, ''))) not between 2 and 100
    or char_length(btrim(coalesce(p_topic, ''))) not between 3 and 300
    or p_language_code is null or p_language_code not in ('en-IN', 'hi-IN', 'kn-IN')
    or p_target_duration_seconds is null or p_target_duration_seconds not in (30, 60)
    or p_visual_style is null or p_visual_style not in ('illustrated', 'editorial', 'storybook')
    or p_difficulty is null or p_difficulty not in ('foundational', 'standard', 'advanced')
    or (v_chapter is not null and char_length(v_chapter) > 200) then
    raise exception 'Check the class, subject, topic and language.' using hint = 'cloud_lesson_invalid';
  end if;

  -- (1) Resolved once, before the lock, because it does not depend on it.
  v_school := public.current_school_id();

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('cloud_lesson_reserve:' || v_owner, 0)
  );
  v_key := p_class_level::text || '|' || lower(regexp_replace(btrim(p_subject), '\s+', ' ', 'g'))
    || '|' || lower(regexp_replace(btrim(p_topic), '\s+', ' ', 'g'))
    || '|' || p_target_duration_seconds::text;

  -- Repeated clicks and the caller's own finished copy stay owner-scoped: a
  -- colleague's in-progress job is not this caller's job to return.
  select * into v_project from public.cloud_lesson_projects
  where owner_id = v_owner and content_key = v_key and visual_style = p_visual_style
    and language_code = p_language_code and curriculum_version = v_curriculum
    and generator_version = v_generator and difficulty = p_difficulty
    and chapter is not distinct from v_chapter
    and status in ('succeeded', 'preparing', 'generating_images', 'generating_videos', 'assembling')
  order by (status = 'succeeded') desc, created_at desc limit 1;
  if found then return next v_project; return; end if;

  -- Only audited source plans with every scene ready can be reused.
  select p.* into v_source from public.cloud_lesson_projects p
  where
    -- (2) the caller's own, or anything their school already paid for
    (p.owner_id = v_owner or (v_school is not null and p.school_id = v_school))
    and p.content_key = v_key and p.visual_style = p_visual_style
    and p.language_code = p_language_code
    -- (3) a source from a superseded syllabus or an older model is not reusable
    and p.curriculum_version = v_curriculum and p.generator_version = v_generator
    and p.difficulty = p_difficulty and p.chapter is not distinct from v_chapter
    and p.status = 'succeeded' and p.reused_from_project_id is null
    and exists (
      select 1 from public.cloud_lesson_jobs j
      where j.project_id = p.id and j.kind = 'prepare' and j.status = 'succeeded'
        and jsonb_typeof(j.output_metadata -> 'sourcePlan') = 'object'
    )
    and (
      select pg_catalog.count(*) from public.cloud_lesson_scenes s
      where s.project_id = p.id and s.status = 'succeeded' and s.image_url is not null
    ) = p_target_duration_seconds / 7.5
    and not exists (
      select 1 from public.cloud_lesson_scenes s
      where s.project_id = p.id and s.motion_mode = 'animate'
        and not exists (
          select 1 from public.cloud_lesson_jobs j
          where j.scene_id = s.id and j.kind = 'video' and j.status = 'succeeded'
            and coalesce(j.output_metadata ->> 'rawVideoUrl', '') ~ '^https://'
        )
    )
    and not exists (
      select 1 from public.cloud_lesson_shots t where t.project_id = p.id and t.image_url is null
    )
  -- The caller's own copy wins ties, so a teacher reuses their own work before
  -- a colleague's and the lesson they see is the one they made.
  order by (p.owner_id = v_owner) desc, p.completed_at desc limit 1;

  select * into v_project from private.reserve_cloud_lesson_uncached(
    p_class_level, p_subject, p_topic, p_language_code, p_target_duration_seconds);
  update public.cloud_lesson_projects
  set visual_style = p_visual_style, school_id = v_school, chapter = v_chapter,
      difficulty = p_difficulty, curriculum_version = v_curriculum, generator_version = v_generator
  where id = v_project.id returning * into v_project;
  update public.cloud_lesson_jobs
  set parameters = parameters || jsonb_build_object('visualStyle', p_visual_style)
  where project_id = v_project.id and kind = 'prepare';
  if v_source.id is not null then
    update public.cloud_lesson_projects set reused_from_project_id = v_source.id
    where id = v_project.id returning * into v_project;
  end if;
  return next v_project;
end; $$;
revoke all on function public.reserve_cloud_lesson(smallint, text, text, text, smallint, text, text, text)
  from public, anon, authenticated, service_role;
grant execute on function public.reserve_cloud_lesson(smallint, text, text, text, smallint, text, text, text)
  to authenticated;

-- ── Completion ──────────────────────────────────────────────────────────────
-- The re-validation at completion has to accept the same sources the
-- reservation did, or a school-reused lesson fails at the last step. Everything
-- else is as 20261011150000 left it.

create or replace function public.complete_cloud_lesson_preparation(
  p_job_id uuid, p_worker_id text, p_title text, p_learning_objective text, p_narration_text text,
  p_narration_url text, p_narration_duration_seconds numeric, p_scenes jsonb,
  p_cost_usd numeric default 0, p_output_metadata jsonb default '{}'::jsonb
) returns boolean language plpgsql security definer set search_path = '' as $$
declare
  v_ok boolean;
  v_project public.cloud_lesson_projects;
  v_scene record;
  v_raw text;
begin
  v_ok := private.complete_cloud_lesson_preparation_original(
    p_job_id, p_worker_id, p_title, p_learning_objective, p_narration_text,
    p_narration_url, p_narration_duration_seconds, p_scenes, p_cost_usd, p_output_metadata);
  if not v_ok then return false; end if;
  select p.* into v_project from public.cloud_lesson_projects p
    join public.cloud_lesson_jobs j on j.project_id = p.id where j.id = p_job_id;
  if v_project.reused_from_project_id is null or v_project.status <> 'generating_images' then
    return true;
  end if;
  -- Owner OR same school, matching the reservation's own scope rule.
  if not exists (
    select 1 from public.cloud_lesson_projects p
    where p.id = v_project.reused_from_project_id
      and (
        p.owner_id = v_project.owner_id
        or (v_project.school_id is not null and p.school_id = v_project.school_id)
      )
      and p.status = 'succeeded' and p.content_key = v_project.content_key
      and p.visual_style = v_project.visual_style
      and p.curriculum_version = v_project.curriculum_version
      and p.generator_version = v_project.generator_version
  ) then
    raise exception 'Visual reuse source is unavailable';
  end if;
  delete from public.cloud_lesson_jobs
  where project_id = v_project.id and kind = 'image' and status = 'queued';
  for v_scene in
    select n.id, n.scene_index, s.image_url, s.motion_mode, s.id as source_scene_id
    from public.cloud_lesson_scenes n
    join public.cloud_lesson_scenes s
      on s.scene_index = n.scene_index and s.project_id = v_project.reused_from_project_id
    where n.project_id = v_project.id
  loop
    select j.output_metadata ->> 'rawVideoUrl' into v_raw from public.cloud_lesson_jobs j
      where j.scene_id = v_scene.source_scene_id and j.kind = 'video' and j.status = 'succeeded';
    if v_scene.image_url is null or (v_scene.motion_mode = 'animate' and v_raw is null) then
      raise exception 'Reusable visuals are incomplete';
    end if;
    update public.cloud_lesson_scenes
    set image_url = v_scene.image_url, motion_mode = v_scene.motion_mode, status = 'queued_video'
    where id = v_scene.id;
    insert into public.cloud_lesson_jobs
      (owner_id, project_id, scene_id, kind, source_image_url, max_attempts, parameters)
    values (v_project.owner_id, v_project.id, v_scene.id, 'video', v_scene.image_url, 2,
      jsonb_build_object('sceneIndex', v_scene.scene_index, 'motionMode', v_scene.motion_mode,
        'clipSeconds', 5, 'slotSeconds', 7.5,
        'reusedFromProjectId', v_project.reused_from_project_id, 'reusedRawVideoUrl', v_raw));
  end loop;
  update public.cloud_lesson_projects set status = 'generating_videos' where id = v_project.id;
  return true;
end; $$;
revoke all on function public.complete_cloud_lesson_preparation(
  uuid, text, text, text, text, text, numeric, jsonb, numeric, jsonb)
  from public, anon, authenticated, service_role;
grant execute on function public.complete_cloud_lesson_preparation(
  uuid, text, text, text, text, text, numeric, jsonb, numeric, jsonb) to service_role;
