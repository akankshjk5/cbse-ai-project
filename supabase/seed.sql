-- Local development seed. Runs automatically on `npm run db:reset`.
-- NEVER run this against a hosted project.
--
-- Identity lives at Clerk, so there is no user row to seed. Replace the id
-- below with your own Clerk user id (`clerk users list --json`, or copy it from
-- the dashboard) to see this deck in your own signed-in session.

do $$
declare
  dev_user_id  text := 'user_seed_replace_me';
  demo_deck_id uuid := '00000000-0000-4000-8000-0000000000d1';
begin
  if exists (select 1 from public.decks where id = demo_deck_id) then
    return;
  end if;

  insert into public.profiles (id) values (dev_user_id) on conflict (id) do nothing;

  insert into public.decks (id, owner_id, title, topic, audience, tone, status, visibility, source_prompt)
  values (
    demo_deck_id, dev_user_id, 'Seeded demo deck', 'Retrieval-augmented decks',
    'Engineering leads', 'confident', 'ready', 'unlisted',
    'A short deck explaining how the generation pipeline works.'
  );

  insert into public.slides (deck_id, position, layout, title, blocks)
  values
    (demo_deck_id, 0, 'title', 'Seeded demo deck',
     '[{"type":"text","value":"Generated by supabase/seed.sql"}]'::jsonb),
    (demo_deck_id, 1, 'title-body', 'How it works',
     '[{"type":"bullet","value":"Outline"},{"type":"bullet","value":"Research"},{"type":"bullet","value":"Design"}]'::jsonb),
    (demo_deck_id, 2, 'closing', 'Questions?', '[]'::jsonb);
end $$;
